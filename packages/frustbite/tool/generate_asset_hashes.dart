import 'dart:io';

import 'package:frustbite/src/hook/download_asset.dart';
import 'package:frustbite/src/hook/targets.dart';
import 'package:frustbite/src/hook/version.dart';

/// Regenerates `lib/src/hook/hashes.dart`, the only file this tool writes.
///
/// ```sh
/// dart tool/generate_asset_hashes.dart [<dir>]
/// dart tool/generate_asset_hashes.dart --tag <release-tag>
/// ```
///
/// With `<dir>` the hashes are computed from the release files in that
/// directory (for example the output of `tool/build.dart`). Without it, the
/// files are downloaded over HTTPS from the release `--tag` (default
/// [version]). Every supported target's file must be present.
Future<void> main(List<String> args) async {
  String? directory;
  var tag = version;
  for (var i = 0; i < args.length; i++) {
    if (args[i] == '--tag' && i + 1 < args.length) {
      tag = args[++i];
    } else if (!args[i].startsWith('--') && directory == null) {
      directory = args[i];
    } else {
      stderr.writeln(
        'Usage: dart tool/generate_asset_hashes.dart [<dir> | --tag <tag>]',
      );
      exit(64);
    }
  }

  final fileNames = [
    for (final (os, architecture, iOSSdk) in supportedTargets)
      assetFileName(os, architecture, iOSSdk),
  ]..sort();

  final Directory source;
  Directory? temporary;
  if (directory != null) {
    source = Directory(directory);
  } else {
    temporary = await Directory.systemTemp.createTemp('frustbite_assets_');
    source = temporary;
    await _downloadAll(tag, fileNames, source);
  }

  try {
    final hashes = <String, String>{};
    for (final fileName in fileNames) {
      final file = File.fromUri(source.uri.resolve(fileName));
      if (!file.existsSync()) {
        stderr.writeln('Missing release file: ${file.path}');
        exit(1);
      }
      hashes[fileName] = await hashAsset(file);
    }
    await _writeHashesFile(hashes);
  } finally {
    temporary?.deleteSync(recursive: true);
  }
}

Future<void> _downloadAll(
  String tag,
  List<String> fileNames,
  Directory into,
) async {
  final client = HttpClient();
  try {
    for (final fileName in fileNames) {
      final uri = Uri.parse(
        'https://github.com/sb-dor/frustbite/releases/download/$tag/$fileName',
      );
      final response = await (await client.getUrl(uri)).close();
      if (response.statusCode != HttpStatus.ok) {
        await response.drain<void>();
        stderr.writeln(
          'Downloading $uri failed with HTTP ${response.statusCode}',
        );
        exit(1);
      }
      await response.pipe(File.fromUri(into.uri.resolve(fileName)).openWrite());
    }
  } finally {
    client.close();
  }
}

Future<void> _writeHashesFile(Map<String, String> hashes) async {
  final file = File.fromUri(
    Platform.script.resolve('../lib/src/hook/hashes.dart'),
  );
  final buffer = StringBuffer('''
// THIS FILE IS AUTOGENERATED. TO UPDATE, RUN
//    dart tool/generate_asset_hashes.dart

/// sha256 of each release asset, keyed by file name.
const assetHashes = <String, String>{
''');
  for (final entry in hashes.entries) {
    buffer.writeln("  '${entry.key}': '${entry.value}',");
  }
  buffer.writeln('};');
  await file.writeAsString(buffer.toString());
  final format = await Process.run(Platform.executable, ['format', file.path]);
  if (format.exitCode != 0) {
    throw StateError('dart format failed: ${format.stderr}');
  }
  stdout.writeln('Wrote ${file.path}');
}
