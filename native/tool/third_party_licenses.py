#!/usr/bin/env python3
"""Generates THIRD_PARTY_LICENSES.md from the Rust dependency graph of native/.

Run from anywhere:

    python3 -I native/tool/third_party_licenses.py          # (re)write both copies
    python3 -I native/tool/third_party_licenses.py --check  # fail if either copy is stale

The graph is every non-dev crate (normal + build dependencies) with default
features, resolved for a native target and for wasm32-unknown-unknown; the
union is listed. License texts are read from the crate sources that cargo
fetched (cargo metadata gives their location), so run `cargo fetch` first on a
clean machine. A crate without any license file fails the run, unless it is in
FALLBACK_MIT below (the upstream crate ships no license file; its Cargo.toml
declares "MIT OR Apache-2.0" and we reproduce the MIT text).

Two copies are kept in sync: the repository root (GitHub / release asset) and
packages/frustbite/ (shipped with the pub package).
"""
import hashlib
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
NATIVE = os.path.dirname(HERE)
REPO = os.path.dirname(NATIVE)
OUTPUTS = [
    os.path.join(REPO, "THIRD_PARTY_LICENSES.md"),
    os.path.join(REPO, "packages", "frustbite", "THIRD_PARTY_LICENSES.md"),
]
TARGETS = ["aarch64-apple-darwin", "wasm32-unknown-unknown"]

# Crates that ship no license file in their crates.io package. Copyright holder
# comes from the Cargo.toml authors field.
FALLBACK_MIT = {"lofty", "lofty_attr", "ogg_pager"}

MIT_TEMPLATE = """MIT License

Copyright (c) {holder}

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.
"""

LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "UNLICENSE", "NOTICE")

HEADER = """# Third-party licenses

The prebuilt frustbite binaries (the `libfrustbite_*` native libraries and
`frustbite.wasm`) statically include the Rust crates listed below. frustbite
itself is MIT licensed (see `LICENSE`). This file is generated by
`native/tool/third_party_licenses.py` from `native/Cargo.lock`; do not edit it
by hand.

The list covers every non-dev dependency of the `native/` crate with default
features, for native targets and for `wasm32-unknown-unknown`. Some build-time
only crates (procedural macros) are listed too; they are not part of the
binaries.

## Source availability (MPL-2.0)

The `symphonia` crates are licensed under the Mozilla Public License 2.0. The
unmodified source of the exact version linked into frustbite (0.6.1) is
available from:

- https://crates.io/crates/symphonia/0.6.1 (and the `symphonia-*` crates at the
  same version)
- https://github.com/pdeljanov/Symphonia

frustbite does not modify the symphonia sources. Recipients may obtain,
modify and rebuild them under the terms of the MPL-2.0 text below. The
frustbite source (https://github.com/sb-dor/frustbite) shows how to rebuild the
binaries with a different symphonia version.

## Crates
"""


def run_metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", target],
        cwd=NATIVE, check=True, capture_output=True, text=True,
    ).stdout
    return json.loads(out)


def non_dev_closure(meta):
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    seen, stack = set(), [meta["resolve"]["root"]]
    while stack:
        pid = stack.pop()
        if pid in seen:
            continue
        seen.add(pid)
        for dep in nodes[pid]["deps"]:
            if any(k["kind"] != "dev" for k in dep["dep_kinds"]):
                stack.append(dep["pkg"])
    return [packages[i] for i in seen]


def read_license_files(pkg):
    crate_dir = os.path.dirname(pkg["manifest_path"])
    names = sorted(
        n for n in os.listdir(crate_dir)
        if n.upper().startswith(LICENSE_PREFIXES)
        and os.path.isfile(os.path.join(crate_dir, n))
    )
    texts = []
    for n in names:
        with open(os.path.join(crate_dir, n), encoding="utf-8") as f:
            texts.append((n, f.read().replace("\r\n", "\n").strip("\n") + "\n"))
    return texts


def fallback_text(pkg):
    authors = pkg.get("authors") or []
    if not authors:
        sys.exit(f"error: {pkg['name']} has no authors for the fallback license")
    holder = ", ".join(a.split("<")[0].strip() for a in authors)
    return [("MIT (standard text)", MIT_TEMPLATE.format(holder=holder))]


def generate():
    crates = {}
    for target in TARGETS:
        for pkg in non_dev_closure(run_metadata(target)):
            if pkg["name"] == "frustbite":
                continue
            crates[(pkg["name"], pkg["version"])] = pkg
    errors = []
    entries = []  # (name, version, license, repository, [(file, text)])
    for (name, version), pkg in sorted(crates.items()):
        files = read_license_files(pkg)
        if not files:
            if name in FALLBACK_MIT:
                files = fallback_text(pkg)
            else:
                errors.append(f"{name} {version}: no license file found")
                continue
        if not pkg.get("license"):
            errors.append(f"{name} {version}: no SPDX license expression")
            continue
        entries.append((name, version, pkg["license"], pkg.get("repository"), files))
    if errors:
        sys.exit("error:\n  " + "\n  ".join(errors))

    # Group identical license texts so the common ones (Apache-2.0, MPL-2.0,
    # ...) appear once; copyright lines make most MIT texts unique.
    by_hash = {}
    for name, version, _, _, files in entries:
        for fname, text in files:
            h = hashlib.sha256(text.encode()).hexdigest()
            by_hash.setdefault(h, {"text": text, "users": []})["users"].append(
                f"{name} {version}")

    out = [HEADER]
    out.append("| Crate | Version | License | Source |")
    out.append("| --- | --- | --- | --- |")
    for name, version, lic, repo, _ in entries:
        out.append(f"| {name} | {version} | {lic} | {repo or 'https://crates.io/crates/' + name} |")
    out.append("")
    out.append("## License texts")
    texts = sorted(by_hash.values(), key=lambda v: (v["users"][0], v["text"]))
    for i, v in enumerate(texts, 1):
        out.append("")
        out.append(f"### License text {i}")
        out.append("")
        out.append("Applies to: " + ", ".join(sorted(v["users"])) + ".")
        out.append("")
        out.append("~~~~text")
        out.append(v["text"].rstrip("\n"))
        out.append("~~~~")
    return "\n".join(out) + "\n"


def main():
    check = "--check" in sys.argv[1:]
    content = generate()
    if check:
        stale = []
        for path in OUTPUTS:
            try:
                with open(path, encoding="utf-8") as f:
                    if f.read() == content:
                        continue
            except FileNotFoundError:
                pass
            stale.append(os.path.relpath(path, REPO))
        if stale:
            sys.exit("error: stale third-party license file(s): " + ", ".join(stale)
                     + "\nrun: python3 -I native/tool/third_party_licenses.py")
        print("third-party license files are up to date")
        return
    for path in OUTPUTS:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(content)
        print("wrote", os.path.relpath(path, REPO))


if __name__ == "__main__":
    main()
